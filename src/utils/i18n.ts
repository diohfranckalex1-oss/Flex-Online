export const getTranslation = (langCode: string, key: string, fallback?: string): string => {
  const langDict = TRANSLATIONS[langCode];
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  // Fallback to French
  if (TRANSLATIONS['fr'] && TRANSLATIONS['fr'][key]) {
    return TRANSLATIONS['fr'][key];
  }
  // Fallback to English
  if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
    return TRANSLATIONS['en'][key];
  }
  return fallback || key;
};

// Filter & search languages seamlessly by name, native name, code or region
export const searchSupportedLanguages = (query: string, categoryFilter: 'all' | 'african_local' | 'international' = 'all'): LanguageOption[] => {
  const q = query.toLowerCase().trim();
  return SUPPORTED_LANGUAGES.filter((lang) => {
    const matchesCategory = categoryFilter === 'all' || lang.category === categoryFilter;
    if (!matchesCategory) return false;
    if (!q) return true;
    return (
      lang.name.toLowerCase().includes(q) ||
      lang.nativeName.toLowerCase().includes(q) ||
      lang.code.toLowerCase().includes(q) ||
      lang.region.toLowerCase().includes(q)
    );
  });
};

// Speech synthesis helper for language preview
export const speakLanguageGreeting = (lang: LanguageOption) => {
  if (typeof window === 'undefined' || !('speechSynthesis' in window)) return;
  try {
    window.speechSynthesis.cancel();
    const utterance = new SpeechSynthesisUtterance(
      `Flex Online en ${lang.name} (${lang.nativeName}). Bienvenue !`
    );
    utterance.rate = 1.0;
    utterance.pitch = 1.0;
    // Map standard BCP-47 codes when possible
    const bcpMap: Record<string, string> = {
      fr: 'fr-FR', en: 'en-US', es: 'es-ES', ar: 'ar-SA', pt: 'pt-BR',
      de: 'de-DE', zh: 'zh-CN', ja: 'ja-JP', ru: 'ru-RU', hi: 'hi-IN',
      it: 'it-IT', tr: 'tr-TR', ko: 'ko-KR', nl: 'nl-NL', vi: 'vi-VN',
      sw: 'sw-TZ'
    };
    if (bcpMap[lang.code]) {
      utterance.lang = bcpMap[lang.code];
    }
    window.speechSynthesis.speak(utterance);
  } catch (e) {
    console.warn('SpeechSynthesis error:', e);
  }
};
